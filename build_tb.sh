#!/usr/bin/env bash

set -euo pipefail

script_dir=$(CDPATH= cd -- "$(dirname "$0")" && pwd)
repo_root=$(CDPATH= cd -- "$script_dir" && pwd)
source_file="$repo_root/compiler/tb/tb.tb"
build_root="$repo_root/.build/stage2"
stage1_ll="$build_root/tb_stage1.ll"
stage1_bin="$build_root/tb_stage1"
stage2_ll="$build_root/tb_stage2.ll"
output_dir="$repo_root/bin"
output_bin="$output_dir/tb"

mkdir -p "$build_root" "$output_dir"

echo "[1/5] embed compiler runtime sources"
python3 - "$repo_root" <<'PY'
from pathlib import Path
import os
import re
import sys

repo_root = Path(sys.argv[1])
version = os.environ.get('TB_VERSION', 'dev')
if version != 'dev' and not re.fullmatch(r'[0-9]+\.[0-9]+\.[0-9]+(?:-[A-Za-z0-9][A-Za-z0-9.-]*)?', version):
    raise SystemExit(f'Invalid TB_VERSION: {version!r}')
helpers = sorted((repo_root / 'compiler/tb/llvm_helpers').glob('*.ll'))
if not helpers:
    raise SystemExit('No LLVM helper templates found')

def tb_string(value):
    return "'" + (value.replace('\\', '\\\\').replace("'", "\\'")
                  .replace('\n', '\\n').replace('\r', '\\r')
                  .replace('\t', '\\t')) + "'"

def source_text(path):
    text = path.read_bytes().decode('ascii')
    if '\0' in text:
        raise SystemExit(f'NUL byte in compiler runtime source: {path}')
    return text

lines = [
    '# Generated by build_tb.sh from compiler runtime sources; do not edit.',
    'string tb_compiler_version():',
    f'    return {tb_string(version)}',
    '',
    'string llvm_embedded_helper_text(string name):',
]
for helper in helpers:
    lines.append(f'    if (name == {tb_string(helper.name)}):')
    lines.append(f'        return {tb_string(source_text(helper))}')
lines.append("    throw 'unknown embedded LLVM helper: ' + name")

runtime = repo_root / 'compiler/tb/runtime'
header = source_text(runtime / 'thread_pool_composite_runtime.h')
include = '#include "thread_pool_composite_runtime.h"'
lines.extend(['', 'string llvm_embedded_runtime_text(string name):'])
for name in ('thread_pool_runtime.c', 'thread_pool_composite_runtime.c'):
    text = source_text(runtime / name)
    if text.count(include) != 1:
        raise SystemExit(f'Expected one composite runtime header include: {name}')
    # Each emitted C source is self-contained; no external header is needed.
    text = text.replace(include, header)
    lines.append(f'    if (name == {tb_string(name)}):')
    lines.append(f'        return {tb_string(text)}')
lines.append("    throw 'unknown embedded C runtime: ' + name")
output = repo_root / 'compiler/tb/llvm_helpers_generated.tb'
output.write_text('\n'.join(lines) + '\n', encoding='ascii')
PY

echo "[2/5] build stage1 llvm"
(
  cd "$repo_root"
  python3 compiler/python/tb.py "$source_file" "$stage1_ll"
)

echo "[3/5] link stage1 compiler"
clang -O2 "$stage1_ll" -o "$stage1_bin"

echo "[4/5] build stage2 llvm"
"$stage1_bin" "$source_file" "$stage2_ll"

echo "[5/5] link self-hosted compiler"
clang -O2 "$stage2_ll" -o "$output_bin"

echo "Built self-hosted tb compiler: $output_bin"
echo "Temporary build files: $build_root"
